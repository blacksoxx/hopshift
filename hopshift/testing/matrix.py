"""Support matrix: which source -> target pairs hopshift supports and how far each is proven.

`support.yaml` at the repository root declares the pairs; this module loads it, cross-checks
every name against the source and target registries, and renders `docs/support-matrix.md`.
`hopshift matrix render` writes the document, `hopshift matrix check` fails when it is stale
(CI runs the check in the lint job).

Rows that are commented out in the YAML (a target that is still being built) are tolerated:
the parser never sees them, and `pending_pairs` surfaces them so the check can hint when both
sides have since been registered.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from hopshift.sources import registry as sources
from hopshift.targets import registry as targets
from hopshift.testing._common import REPO_ROOT

TIERS: tuple[str, ...] = ("tested", "validated", "experimental")
LEGEND: dict[str, str] = {
    "tested": "exercised against real infrastructure (a lab or a cloud account) in addition to the CI validation",
    "validated": "rendered and validated by terraform validate, tflint and OPA in CI",
    "experimental": "renders, not yet validated end to end",
}
_BADGE_COLOURS: dict[str, str] = {"tested": "2ea44f", "validated": "1f6feb", "experimental": "d4a72c"}
_PAIR_KEYS = {"source", "target", "tier", "evidence", "notes"}

SUPPORT_FILE = REPO_ROOT / "support.yaml"
MATRIX_DOC = REPO_ROOT / "docs" / "support-matrix.md"
GENERATED_MARKER = "<!-- Generated by `hopshift matrix render` from support.yaml. Do not edit by hand. -->"


class SupportMatrixError(ValueError):
    """support.yaml is malformed or names something the registries do not know."""


@dataclass(frozen=True)
class SupportPair:
    source: str
    target: str
    tier: str
    evidence: str = ""
    notes: str = ""

    def to_dict(self) -> dict[str, str]:
        return {"source": self.source, "target": self.target, "tier": self.tier, "evidence": self.evidence, "notes": self.notes}


@dataclass
class SupportMatrix:
    pairs: list[SupportPair] = field(default_factory=list)
    path: Path | None = None

    def sources(self) -> list[str]:
        return sorted(set(sources.names()) | {pair.source for pair in self.pairs})

    def targets(self) -> list[str]:
        return sorted(set(targets.names()) | {pair.target for pair in self.pairs})

    def get(self, source: str, target: str) -> SupportPair | None:
        return next((pair for pair in self.pairs if pair.source == source and pair.target == target), None)

    def tier(self, source: str, target: str) -> str | None:
        pair = self.get(source, target)
        return pair.tier if pair else None

    def to_dict(self) -> dict[str, Any]:
        return {"pairs": [pair.to_dict() for pair in self.pairs]}


def load(path: str | Path = SUPPORT_FILE, *, check_registry: bool = True) -> SupportMatrix:
    """Parse and validate support.yaml. Unknown source/target names, bad tiers, duplicate
    pairs and unexpected keys raise SupportMatrixError with every problem listed."""
    support_path = Path(path)
    if not support_path.exists():
        raise SupportMatrixError(f"{support_path} does not exist")
    data = yaml.safe_load(support_path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict) or not isinstance(data.get("pairs"), list):
        raise SupportMatrixError(f"{support_path.name}: expected a mapping with a `pairs` list")

    known_sources = set(sources.names())
    known_targets = set(targets.names())
    problems: list[str] = []
    pairs: list[SupportPair] = []
    seen: set[tuple[str, str]] = set()

    for index, raw in enumerate(data["pairs"]):
        where = f"pairs[{index}]"
        if not isinstance(raw, dict):
            problems.append(f"{where}: must be a mapping with source, target and tier")
            continue
        unexpected = sorted(set(map(str, raw)) - _PAIR_KEYS)
        if unexpected:
            problems.append(f"{where}: unexpected keys {', '.join(unexpected)} (allowed: {', '.join(sorted(_PAIR_KEYS))})")
        source = str(raw.get("source") or "").strip().lower()
        target = str(raw.get("target") or "").strip().lower()
        tier = str(raw.get("tier") or "").strip().lower()
        missing = [key for key, value in (("source", source), ("target", target), ("tier", tier)) if not value]
        if missing:
            problems.append(f"{where}: missing {', '.join(missing)}")
            continue
        if tier not in TIERS:
            problems.append(f"{where}: tier {tier!r} must be one of {', '.join(TIERS)}")
        if check_registry and source not in known_sources:
            problems.append(f"{where}: unknown source {source!r} (registered: {', '.join(sorted(known_sources)) or 'none'})")
        if check_registry and target not in known_targets:
            problems.append(f"{where}: unknown target {target!r} (registered: {', '.join(sorted(known_targets)) or 'none'})")
        if (source, target) in seen:
            problems.append(f"{where}: duplicate pair {source} -> {target}")
        seen.add((source, target))
        pairs.append(
            SupportPair(
                source=source, target=target, tier=tier,
                evidence=_text(raw.get("evidence")), notes=_text(raw.get("notes")),
            )
        )

    if problems:
        raise SupportMatrixError(f"{support_path.name}: " + "; ".join(problems))
    return SupportMatrix(pairs=sorted(pairs, key=lambda pair: (pair.source, pair.target)), path=support_path)


_COMMENT_ROW_START = re.compile(r"^\s*#\s*-\s*([a-z_]+):\s*(.*?)\s*$")
_COMMENT_ROW_FIELD = re.compile(r"^\s*#\s+([a-z_]+):\s*(.*?)\s*$")


def pending_pairs(path: str | Path = SUPPORT_FILE) -> list[SupportPair]:
    """Pairs declared as commented-out rows (`# - source: ...` followed by `#   target: ...`).

    They are not part of the matrix; they document work in progress and let `check` hint when
    the names become registered.
    """
    support_path = Path(path)
    if not support_path.exists():
        return []
    rows: list[dict[str, str]] = []
    current: dict[str, str] | None = None
    for line in support_path.read_text(encoding="utf-8").splitlines():
        start = _COMMENT_ROW_START.match(line)
        if start:
            current = {start.group(1): _unquote(start.group(2))}
            rows.append(current)
            continue
        if current is not None:
            item = _COMMENT_ROW_FIELD.match(line)
            if item:
                current[item.group(1)] = _unquote(item.group(2))
                continue
        current = None
    pending: list[SupportPair] = []
    for row in rows:
        source = row.get("source", "").strip().lower()
        target = row.get("target", "").strip().lower()
        if source and target:
            tier = row.get("tier", "").strip().lower() or "experimental"
            pending.append(SupportPair(source, target, tier if tier in TIERS else "experimental", row.get("evidence", ""), row.get("notes", "")))
    return pending


def badge(tier: str) -> str:
    return f"![{tier}](https://img.shields.io/badge/{tier}-{_BADGE_COLOURS.get(tier, '9e9e9e')})"


def render(matrix: SupportMatrix) -> str:
    """Markdown document: legend, sources x targets grid with tier badges, pair details."""
    source_names = matrix.sources()
    target_names = matrix.targets()
    lines: list[str] = [
        "# Support matrix",
        "",
        GENERATED_MARKER,
        "",
        "Which source platforms hopshift can migrate to which targets, and how far each pair has",
        "been proven. The pairs are declared in `support.yaml`; every name is checked against the",
        "source and target registries, so a row can only exist for something that is actually",
        "registered. How a pair moves up a tier is described in [plugins.md](plugins.md).",
        "",
        "## Legend",
        "",
        "| Tier | Meaning |",
        "|---|---|",
    ]
    for tier in TIERS:
        lines.append(f"| {badge(tier)} | {LEGEND[tier]} |")
    lines += ["", "## Sources x targets", ""]
    lines.append("| Source \\ Target | " + " | ".join(f"`{name}`" for name in target_names) + " |")
    lines.append("|---|" + "|".join("---" for _ in target_names) + "|")
    for source in source_names:
        cells = [badge(pair.tier) if (pair := matrix.get(source, target)) else "-" for target in target_names]
        lines.append(f"| `{source}` | " + " | ".join(cells) + " |")
    lines += [
        "",
        "`-` means no declared support: the pair may render, but nothing vouches for it.",
        "",
        "## Pairs",
        "",
        "| Source | Target | Tier | Evidence | Notes |",
        "|---|---|---|---|---|",
    ]
    for pair in matrix.pairs:
        lines.append(
            f"| `{pair.source}` | `{pair.target}` | {pair.tier} | {_cell(pair.evidence)} | {_cell(pair.notes)} |"
        )
    lines += [
        "",
        "## Keeping this page current",
        "",
        "Edit `support.yaml`, then run `hopshift matrix render`. CI runs `hopshift matrix check` and fails",
        "when this file does not match the YAML.",
        "",
    ]
    return "\n".join(lines)


def write(doc_path: str | Path = MATRIX_DOC, support_path: str | Path = SUPPORT_FILE) -> Path:
    target = Path(doc_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(load(support_path)), encoding="utf-8", newline="\n")
    return target


def check(doc_path: str | Path = MATRIX_DOC, support_path: str | Path = SUPPORT_FILE) -> list[str]:
    """Problems that must fail CI: invalid support.yaml, or a rendered document that is stale."""
    try:
        matrix = load(support_path)
    except SupportMatrixError as exc:
        return [str(exc)]
    document = Path(doc_path)
    if not document.exists():
        return [f"{document} is missing; run `hopshift matrix render`"]
    if document.read_text(encoding="utf-8") != render(matrix):
        return [f"{document} is stale; run `hopshift matrix render`"]
    return []


def hints(support_path: str | Path = SUPPORT_FILE) -> list[str]:
    """Advice that does not fail the check: commented rows whose names are now registered."""
    known_sources = set(sources.names())
    known_targets = set(targets.names())
    notes: list[str] = []
    for pair in pending_pairs(support_path):
        if pair.source in known_sources and pair.target in known_targets:
            notes.append(
                f"{pair.source} -> {pair.target} is commented out in support.yaml but both are registered; "
                "uncomment the row and run `hopshift matrix render`"
            )
    return notes


def _text(value: object) -> str:
    return " ".join(str(value).split()) if value is not None else ""


def _cell(text: str) -> str:
    return text.replace("|", "\\|") if text else ""


def _unquote(text: str) -> str:
    text = text.strip()
    if len(text) >= 2 and text[0] == text[-1] and text[0] in {'"', "'"}:
        return text[1:-1]
    return text
