"""Generate cim/cim.schema.json from the Pydantic models so the two never drift.

    python -m cim.schema_export          # rewrite the file
    python -m cim.schema_export --check  # exit 1 if the file is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from cim.schema import CIM_SCHEMA_VERSION, CanonicalInfrastructureModel

SCHEMA_PATH = Path(__file__).resolve().parent / "cim.schema.json"


def build_json_schema() -> dict:
    schema = CanonicalInfrastructureModel.model_json_schema()
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "cim.schema.json"
    schema["title"] = "CanonicalInfrastructureModel"
    schema["description"] = f"Canonical Infrastructure Model {CIM_SCHEMA_VERSION}; generated by cim.schema_export"
    return schema


def render() -> str:
    return json.dumps(build_json_schema(), indent=2, ensure_ascii=True) + "\n"


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        current = SCHEMA_PATH.read_text(encoding="utf-8") if SCHEMA_PATH.exists() else ""
        if current != rendered:
            print(f"{SCHEMA_PATH} is stale; run: python -m cim.schema_export", file=sys.stderr)
            return 1
        print(f"{SCHEMA_PATH} is up to date")
        return 0
    SCHEMA_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {SCHEMA_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
